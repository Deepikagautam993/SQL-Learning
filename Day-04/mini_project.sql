-- =========================================================
-- STEP 1: CREATE TABLE
-- =========================================================

CREATE TABLE company_sales (
    sale_id INT,
    product_name VARCHAR(50),
    category VARCHAR(50),
    region VARCHAR(50),
    sales_amount INT,
    quantity INT
);



-- =========================================================
-- TABLE UNDERSTANDING
-- =========================================================
-- sale_id       -> Unique ID for each sale
-- product_name  -> Name of product
-- category      -> Product category
-- region        -> Sales region
-- sales_amount  -> Revenue generated
-- quantity      -> Units sold
-- =========================================================



