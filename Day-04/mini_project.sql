-- =========================================================
-- STEP 3: VIEW COMPLETE DATA
-- =========================================================
-- Business Use Case:
-- Used to verify inserted records before analysis
-- =========================================================

SELECT *
FROM company_sales;



-- =========================================================
-- STEP 4: TOTAL COMPANY REVENUE
-- =========================================================
-- Business Use Case:
-- Calculate overall company revenue
-- Used in:
-- - KPI dashboards
-- - Revenue reports
-- - Business performance tracking
-- =========================================================

SELECT
    SUM(sales_amount) AS total_revenue
FROM company_sales;



-- =========================================================
-- STEP 5: TOTAL NUMBER OF ORDERS
-- =========================================================
-- Business Use Case:
-- Calculate total transactions/orders
-- =========================================================

SELECT
    COUNT(*) AS total_orders
FROM company_sales;



-- =========================================================
-- STEP 6: AVERAGE SALES AMOUNT
-- =========================================================
-- Business Use Case:
-- Analyze average order value
-- Helps companies understand customer spending behavior
-- =========================================================

SELECT
    AVG(sales_amount) AS average_sales
FROM company_sales;



-- =========================================================
-- STEP 7: HIGHEST SALE
-- =========================================================
-- Business Use Case:
-- Identify highest transaction value
-- =========================================================

SELECT
    MAX(sales_amount) AS highest_sale
FROM company_sales;



-- =========================================================
-- STEP 8: LOWEST SALE
-- =========================================================
-- Business Use Case:
-- Identify smallest transaction value
-- =========================================================

SELECT
    MIN(sales_amount) AS lowest_sale
FROM company_sales;



-- =========================================================
-- STEP 9: CATEGORY-WISE SALES ANALYSIS
-- =========================================================
-- Business Use Case:
-- Analyze total revenue generated by each category
--
-- Helps companies identify:
-- - Best performing categories
-- - Weak categories
-- - Revenue contribution
-- =========================================================

SELECT
    category,
    SUM(sales_amount) AS total_sales
FROM company_sales
GROUP BY category;



-- =========================================================
-- STEP 10: REGION-WISE SALES REPORT
-- =========================================================
-- Business Use Case:
-- Analyze business performance region-wise
--
-- This type of query is heavily used in:
-- - Sales dashboards
-- - Regional reports
-- - Performance tracking systems
-- =========================================================

SELECT
    region,
    COUNT(*) AS total_orders,
    SUM(sales_amount) AS total_sales,
    AVG(sales_amount) AS average_sales
FROM company_sales
GROUP BY region;



-- =========================================================
-- STEP 11: CATEGORY-WISE KPI REPORT
-- =========================================================
-- Business Use Case:
-- Generate category-level business KPIs
--
-- KPIs Included:
-- - Total Orders
-- - Total Revenue
-- - Average Sales
-- - Highest Sale
-- - Lowest Sale
--
-- This is a REAL Data Analyst style query
-- =========================================================

SELECT
    category,
    COUNT(*) AS total_orders,
    SUM(sales_amount) AS total_revenue,
    AVG(sales_amount) AS average_sales,
    MAX(sales_amount) AS highest_sale,
    MIN(sales_amount) AS lowest_sale
FROM company_sales
GROUP BY category;



-- =========================================================
-- STEP 12: HIGH REVENUE CATEGORIES
-- =========================================================
-- Business Use Case:
-- Identify categories generating high revenue
--
-- HAVING is used because filtering happens
-- AFTER aggregation
-- =========================================================

SELECT
    category,
    SUM(sales_amount) AS total_sales
FROM company_sales
GROUP BY category
HAVING SUM(sales_amount) > 10000;



-- =========================================================
-- STEP 13: REGION-WISE KPI DASHBOARD
-- =========================================================
-- Business Use Case:
-- Generate regional business performance summary
-- =========================================================

SELECT
    region,
    COUNT(*) AS total_orders,
    SUM(sales_amount) AS total_revenue,
    AVG(sales_amount) AS average_sales,
    MAX(sales_amount) AS highest_sale,
    MIN(sales_amount) AS lowest_sale
FROM company_sales
GROUP BY region;



-- =========================================================
-- STEP 14: TOP PERFORMING CATEGORY
-- =========================================================
-- Business Use Case:
-- Find category with highest revenue
--
-- Concepts Used:
-- - GROUP BY
-- - SUM()
-- - ORDER BY
-- - LIMIT
-- =========================================================

SELECT
    category,
    SUM(sales_amount) AS total_sales
FROM company_sales
GROUP BY category
ORDER BY total_sales DESC
LIMIT 1;



-- =========================================================
-- STEP 15: SALES QUANTITY ANALYSIS
-- =========================================================
-- Business Use Case:
-- Analyze total products sold category-wise
-- =========================================================

SELECT
    category,
    SUM(quantity) AS total_quantity_sold
FROM company_sales
GROUP BY category;



